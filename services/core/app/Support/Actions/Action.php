<?php

namespace App\Support\Actions;

/**
 * Маркерный базовый класс для Action (оркестраторов сценариев).
 *
 * Action — это не сервис. Он:
 *  - получает параметры из контроллера (обычно через FormRequest)
 *  - вызывает один или несколько сервисов
 *  - возвращает типизированный DTO или void
 *  - диспатчит доменные события (в будущем)
 *
 * Сервисы содержат бизнес-правила и переиспользуемы.
 * Action — однократный сценарий, привязанный к юзу-кейсу.
 *
 * handle() не объявляется здесь: сигнатура уникальна для каждого
 * сценария, а абстрактная `mixed ...$args` ломает ковариантность
 * возвращаемого типа и теряет типизацию.
 */
abstract class Action {}
